export function isValidLakeWord(rootWord: string, candidate: string): boolean {
  const clean = candidate.trim().toUpperCase();
  const root = rootWord.trim().toUpperCase();
  if (clean.length < 3) return false;
  
  // 1. The 9-letter root word is ALWAYS valid!
  if (clean === root) return true;

  // 2. Check the precomputed dictionary for this root
  const list = NINE_LETTER_VALID_SUBWORDS[root];
  if (list && list.includes(clean)) return true;

  return false;
}
